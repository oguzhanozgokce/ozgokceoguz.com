import { writeFile } from 'node:fs/promises';
import {
  brandColors,
  colorDeclarations,
  schemeCss,
  type BrandColors,
  type ColorMode,
  type ContrastLevel,
  type SchemeSet,
} from '../src/lib/ds/color-scheme.ts';
import { defaultSeed, seedColors, seeds, type Seed } from '../src/lib/seeds.ts';

const style = 'vibrant';
const surfaces = 'neutral';
const contrasts: ContrastLevel[] = ['standard', 'medium', 'high'];
const modes: ColorMode[] = ['light', 'dark'];

function schemesFor(seed: Seed): SchemeSet {
  const set = {} as SchemeSet;
  for (const mode of modes) {
    set[mode] = {} as Record<ContrastLevel, BrandColors>;
    for (const contrast of contrasts) {
      set[mode][contrast] = brandColors({
        seed: seedColors[seed],
        mode,
        style,
        contrast,
        surfaces,
      });
    }
  }
  return set;
}

function block(selectors: string[], colors: BrandColors, indent = '') {
  const list = selectors.map((selector) => `${indent}  ${selector}`).join(',\n');
  return `${indent}:where(\n${list}\n${indent}) {\n${colorDeclarations(colors, `${indent}  `)}\n${indent}}`;
}

function presetCss(seed: Seed) {
  const schemes = schemesFor(seed);
  const root = `html[data-seed='${seed}']`;
  const light = `:is(.light, [data-theme='light'])`;
  const dark = `:is(.dark, [data-theme='dark'])`;
  return [
    block([root, `${root} ${light}`], schemes.light.standard),
    block([`${root}${dark}`, `${root} ${dark}`], schemes.dark.standard),
    [
      '@media (prefers-contrast: more) {',
      block([root, `${root} ${light}`], schemes.light.high, '  '),
      '',
      block([`${root}${dark}`, `${root} ${dark}`], schemes.dark.high, '  '),
      '}',
    ].join('\n'),
  ].join('\n\n');
}

const parts = [
  '/* Generated by scripts/generate-seeds.ts. Do not edit. */',
  schemeCss(schemesFor(defaultSeed)),
  ...seeds.filter((seed) => seed !== defaultSeed).map(presetCss),
];

await writeFile(new URL('../styles/seeds.css', import.meta.url), `${parts.join('\n\n')}\n`);

console.log(`styles/seeds.css: ${seeds.length} seeds, default ${defaultSeed}`);
